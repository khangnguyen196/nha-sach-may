  for each row execute function public.book_authors_touch_book();

-- Tìm kiếm sách không dấu: search_books('dac nhan tam') hoặc search_books('Đắc Nhân')
create or replace function public.search_books(q text, max_results int default 24)
returns setof public.books language sql stable set search_path = '' as $$
  select *
    from public.books
   where is_active
     and search_text like '%' || public.normalize_vi(q) || '%'
   order by sold_count desc, created_at desc
   limit least(max_results, 100);
$$;


