-- Phí ship: 30.000đ, miễn phí cho đơn từ 300.000đ (sửa 2 hằng số này tùy ý)
create or replace function public.place_order(
  p_address_id     bigint,
  p_payment_method public.payment_method default 'cod',
  p_voucher_code   text default null,
  p_note           text default null
)
returns public.orders
language plpgsql security definer set search_path = '' as $$
declare
  c_shipping_fee      constant int := 30000;
  c_free_ship_from    constant int := 300000;

  v_user      uuid := auth.uid();
  v_addr      public.addresses;
  v_voucher   public.vouchers;
  v_item      record;
  v_count     int := 0;
  v_subtotal  int := 0;
  v_shipping  int := 0;
  v_discount  int := 0;
  v_order     public.orders;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select * into v_addr from public.addresses
   where id = p_address_id and user_id = v_user;
  if not found then
    raise exception 'INVALID_ADDRESS';
  end if;

  -- Khóa các dòng sách để 2 người không mua cùng lúc vượt tồn kho
  for v_item in
    select c.quantity, b.id, b.title, b.price, b.stock, b.is_active
      from public.cart_items c
      join public.books b on b.id = c.book_id
     where c.user_id = v_user
     order by b.id
       for update of b
  loop
    if not v_item.is_active then
      raise exception 'BOOK_UNAVAILABLE'
        using detail = json_build_object('book_id', v_item.id, 'title', v_item.title)::text;
    end if;
    if v_item.stock < v_item.quantity then
      raise exception 'OUT_OF_STOCK'
        using detail = json_build_object('book_id', v_item.id, 'title', v_item.title, 'stock', v_item.stock)::text;
    end if;
    v_count    := v_count + 1;
    v_subtotal := v_subtotal + v_item.price * v_item.quantity;
  end loop;

  if v_count = 0 then
    raise exception 'CART_EMPTY';
  end if;

  v_shipping := case when v_subtotal >= c_free_ship_from then 0 else c_shipping_fee end;

  -- Áp mã giảm giá (nếu có)
  if p_voucher_code is not null and btrim(p_voucher_code) <> '' then
    select * into v_voucher from public.vouchers
     where code = upper(btrim(p_voucher_code))
       for update;

    if not found
       or not v_voucher.is_active
       or (v_voucher.starts_at   is not null and now() < v_voucher.starts_at)
       or (v_voucher.ends_at     is not null and now() > v_voucher.ends_at)
       or (v_voucher.usage_limit is not null and v_voucher.used_count >= v_voucher.usage_limit)
    then
      raise exception 'INVALID_VOUCHER';
    end if;

    if v_subtotal < v_voucher.min_order_value then
      raise exception 'VOUCHER_MIN_ORDER'
        using detail = json_build_object('min_order_value', v_voucher.min_order_value)::text;
    end if;

    if v_voucher.discount_type = 'percent' then
      v_discount := v_subtotal * v_voucher.discount_value / 100;
      if v_voucher.max_discount is not null then
        v_discount := least(v_discount, v_voucher.max_discount);
      end if;
    else
      v_discount := v_voucher.discount_value;
    end if;

    v_discount := least(v_discount, v_subtotal);

    update public.vouchers set used_count = used_count + 1 where id = v_voucher.id;
  end if;

  insert into public.orders (
    user_id, payment_method,
    recipient_name, phone, province, ward, street, note,
    subtotal, shipping_fee, discount, total,
    voucher_id, voucher_code
  ) values (
    v_user, p_payment_method,
    v_addr.recipient_name, v_addr.phone, v_addr.province, v_addr.ward, v_addr.street, p_note,
    v_subtotal, v_shipping, v_discount, v_subtotal + v_shipping - v_discount,
    v_voucher.id, v_voucher.code
  )
  returning * into v_order;

  insert into public.order_items (order_id, book_id, title, cover_url, unit_price, quantity)
  select v_order.id, b.id, b.title, b.cover_url, b.price, c.quantity
    from public.cart_items c
    join public.books b on b.id = c.book_id
   where c.user_id = v_user;

  update public.books b
     set stock      = b.stock - c.quantity,
         sold_count = b.sold_count + c.quantity
    from public.cart_items c
   where c.book_id = b.id and c.user_id = v_user;

  delete from public.cart_items where user_id = v_user;

  return v_order;
end;
$$;

-- Khách tự hủy đơn (chỉ khi đơn còn 'pending')
create or replace function public.cancel_order(p_order_id bigint, p_reason text default null)
returns public.orders
language plpgsql security definer set search_path = '' as $$
declare
  v_order public.orders;
begin
  update public.orders
     set status = 'cancelled',
         cancelled_reason = p_reason
   where id = p_order_id
     and user_id = auth.uid()
     and status = 'pending'
  returning * into v_order;

  if not found then
    raise exception 'ORDER_NOT_CANCELLABLE';
  end if;

  return v_order;
end;
$$;


