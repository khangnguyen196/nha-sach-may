-- so-thich-canh-bao P-A (docs/plans/so-thich-canh-bao.md): toàn bộ SQL của cảnh báo nội dung + chặn theo sở thích.
--   1. Kiểu content_warning (5 nhãn cố định). books.content_warnings (≤ 5 nhãn, không phần tử null; trigger bỏ trùng +
--      xếp theo thứ tự enum) + books.content_warnings_reviewed_at (null = chưa xét). Hai cột vào quyền cột update của
--      admin. Khách đọc nhãn như mọi cột công khai của sách.
--   2. content_warning_suggestions: gợi ý nhãn của AI chờ admin duyệt. Chỉ admin đọc / thêm (RLS); đổi trạng thái chỉ
--      qua review_warning_suggestion; tối đa một gợi ý pending / sách.
--   3. user_blocks: mục chặn của thành viên (danh mục / tác giả / NXB / nhãn cảnh báo), chỉ chủ tài khoản đọc / thêm /
--      xóa (admin cũng không đọc: dữ liệu nhạy cảm), ≤ 50 mục / tài khoản (PREFS_LIMIT), không trùng (unique theo kind).
--   4. consume_warning_quota: trừ lượt cho MỘT lượt gọi Gemini của gợi ý cảnh báo (chỉ admin). Đếm CHUNG với Mây
--      (cùng GEMINI_API_KEY + model): gemini:minute, gemini:day; chỉ lấy lượt khi gemini:day ≤ 300 (chừa 100 cho Mây).
--   5. review_warning_suggestion: admin duyệt (ghi nhãn đã sửa vào sách) hoặc bỏ qua (sách thành "đã xét").
-- Chỉ THÊM (kiểu, cột có default, bảng, hàm, policy) → an toàn với bản app đang chạy; chạy TRƯỚC khi app P-B lên.
-- Chạy MỘT lần trong SQL Editor (cả file là một transaction; chạy lần 2 lỗi ở create type, không đổi gì).
-- Không đổi dữ liệu có sẵn (cột mới có default '{}' / null).

begin;

-- 1. Nhãn cảnh báo trên sách
create type public.content_warning as enum ('violence', 'loss', 'self_harm', 'adult', 'other_sensitive');

alter table public.books
  add column if not exists content_warnings public.content_warning[] not null default '{}'
  constraint books_content_warnings_check
  check (cardinality(content_warnings) <= 5 and array_position(content_warnings, null) is null);

alter table public.books
  add column if not exists content_warnings_reviewed_at timestamptz;

-- Admin sửa nhãn ở form sách → cùng danh sách quyền cột với 20261016010000_cover_width.sql + 2 cột mới
revoke update on public.books from anon, authenticated;
grant  update (
  title, slug, subtitle, description, description_en, category_id, publisher_id, isbn,
  price, original_price, stock, cover_url, cover_width, page_count, format, language, published_year,
  weight_grams, dimensions, is_active, is_featured, content_warnings, content_warnings_reviewed_at
) on public.books to authenticated;

-- Bỏ trùng + xếp theo thứ tự khai báo của enum (so sánh mảng / hiện nhãn ổn định). Phần tử null giữ lại để check của
-- bảng từ chối. Trigger thay cho CHECK gọi hàm: authenticated không có usage trên schema private, CHECK gọi hàm private
-- làm admin sửa sách lỗi; trigger security definer chạy bằng quyền owner.
create or replace function private.content_warnings_sorted(p_labels public.content_warning[])
returns public.content_warning[] language sql immutable set search_path = '' as $$
  select case
    when p_labels is null then null
    else coalesce((select array_agg(distinct t.label order by t.label) from unnest(p_labels) as t(label)),
                  '{}'::public.content_warning[])
  end;
$$;

create or replace function private.books_normalize_content_warnings()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.content_warnings := private.content_warnings_sorted(new.content_warnings);
  return new;
end;
$$;

create trigger books_content_warnings before insert or update of content_warnings on public.books
  for each row execute function private.books_normalize_content_warnings();

-- 2. Gợi ý nhãn của AI, chờ admin duyệt
create table public.content_warning_suggestions (
  id           bigint generated by default as identity primary key,
  book_id      bigint not null references public.books(id) on delete cascade,
  labels       public.content_warning[] not null default '{}',
  reason       text not null,
  status       text not null default 'pending' check (status in ('pending', 'approved', 'dismissed')),
  model        text,                       -- model Gemini đã gợi ý (resolveModel)
  created_at   timestamptz not null default now(),
  reviewed_at  timestamptz,
  constraint content_warning_suggestions_labels_check
    check (cardinality(labels) <= 5 and array_position(labels, null) is null),
  constraint content_warning_suggestions_reason_length check (char_length(reason) between 1 and 200),
  constraint content_warning_suggestions_model_length check (model is null or char_length(model) <= 80),
  constraint content_warning_suggestions_reviewed_check check ((status = 'pending') = (reviewed_at is null))
);

create index content_warning_suggestions_book_idx on public.content_warning_suggestions (book_id);
-- Một gợi ý chờ duyệt / sách: lô gợi ý không tạo trùng, admin duyệt đúng một bản
create unique index content_warning_suggestions_one_pending
  on public.content_warning_suggestions (book_id) where status = 'pending';

create or replace function private.content_warning_suggestions_normalize_labels()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.labels := private.content_warnings_sorted(new.labels);
  return new;
end;
$$;

create trigger content_warning_suggestions_labels before insert or update of labels
  on public.content_warning_suggestions
  for each row execute function private.content_warning_suggestions_normalize_labels();

alter table public.content_warning_suggestions enable row level security;

create policy "content_warning_suggestions_admin_select" on public.content_warning_suggestions
  for select to authenticated using ((select public.is_admin()));

create policy "content_warning_suggestions_admin_insert" on public.content_warning_suggestions
  for insert to authenticated with check ((select public.is_admin()));

-- Không update / delete: đổi trạng thái chỉ qua review_warning_suggestion; dọn e2e bằng service role
revoke all on table public.content_warning_suggestions from anon, authenticated;
grant  select on public.content_warning_suggestions to authenticated;
grant  insert (book_id, labels, reason, model) on public.content_warning_suggestions to authenticated;

-- 3. Mục chặn theo sở thích của thành viên
create or replace function private.user_blocks_limit()
returns int language sql immutable set search_path = '' as $$ select 50 $$;

create table public.user_blocks (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  kind          text not null check (kind in ('category', 'author', 'publisher', 'warning')),
  category_id   bigint references public.categories(id) on delete cascade,
  author_id     bigint references public.authors(id) on delete cascade,
  publisher_id  bigint references public.publishers(id) on delete cascade,
  warning       public.content_warning,
  created_at    timestamptz not null default now(),
  -- Đúng một cột đích khác null, khớp kind
  constraint user_blocks_target_check check (
    (category_id is not null) = (kind = 'category')
    and (author_id is not null) = (kind = 'author')
    and (publisher_id is not null) = (kind = 'publisher')
    and (warning is not null) = (kind = 'warning')
  )
);

create index user_blocks_user_idx on public.user_blocks (user_id, created_at);
-- Chống trùng theo từng kind (unique thường trên cả 4 cột không chặn được: NULL khác NULL)
create unique index user_blocks_category_unique  on public.user_blocks (user_id, category_id)  where kind = 'category';
create unique index user_blocks_author_unique    on public.user_blocks (user_id, author_id)    where kind = 'author';
create unique index user_blocks_publisher_unique on public.user_blocks (user_id, publisher_id) where kind = 'publisher';
create unique index user_blocks_warning_unique   on public.user_blocks (user_id, warning)      where kind = 'warning';

-- ≤ user_blocks_limit() mục / tài khoản. Khóa theo user_id trước khi đếm: hai lần thêm song song không cùng vượt.
create or replace function private.user_blocks_check_limit()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended('user_blocks:' || new.user_id::text, 0));

  if (select count(*) from public.user_blocks b where b.user_id = new.user_id) >= private.user_blocks_limit() then
    raise exception 'PREFS_LIMIT'
      using detail = json_build_object('max', private.user_blocks_limit())::text;
  end if;

  return new;
end;
$$;

create trigger user_blocks_limit before insert on public.user_blocks
  for each row execute function private.user_blocks_check_limit();

alter table public.user_blocks enable row level security;

-- Chỉ chủ tài khoản; admin / anon không có policy (danh sách chặn là dữ liệu nhạy cảm). Không update (bỏ chặn = xóa).
create policy "user_blocks_select_own" on public.user_blocks
  for select to authenticated using (user_id = (select auth.uid()));

create policy "user_blocks_insert_own" on public.user_blocks
  for insert to authenticated with check (user_id = (select auth.uid()));

create policy "user_blocks_delete_own" on public.user_blocks
  for delete to authenticated using (user_id = (select auth.uid()));

-- user_id không nằm trong quyền insert: luôn là default auth.uid()
revoke all on table public.user_blocks from anon, authenticated;
grant  select, delete on public.user_blocks to authenticated;
grant  insert (kind, category_id, author_id, publisher_id, warning) on public.user_blocks to authenticated;

-- 4. Hạn mức gợi ý cảnh báo
-- Ngưỡng của bucket CHUNG gemini:day mà gợi ý cảnh báo còn được lấy lượt: 300 = 400 (trần ngày của Mây,
-- CHAT_LIMITS.geminiCallsPerDay) − 100 chừa cho Mây (WARNING_LIMITS.chatReserve). Hằng cứng, không nhận từ app: phiên
-- admin bị lộ không nâng được.
create or replace function private.warning_gemini_day_ceiling()
returns int language sql immutable set search_path = '' as $$ select 300 $$;

-- Trừ lượt cho MỘT lượt gọi Gemini của gợi ý cảnh báo (admin, P-B).
--   Gợi ý cảnh báo gọi Gemini bằng CÙNG khóa GEMINI_API_KEY và CÙNG model với Mây (resolveModel: GEMINI_MODEL nếu
--   nằm trong ALLOWED_MODELS, không thì DEFAULT_MODEL = gemini-3.5-flash-lite). Google tính RPM / RPD theo project của
--   khóa + model (free tier 15 / phút, 500 / ngày) → mỗi lượt gợi ý cộng vào bucket CHUNG gemini:minute + gemini:day
--   như một lượt của Mây. Mây dừng ở 400 / ngày (p_limits của consume_chat_quota), gợi ý dừng sớm hơn ở
--   private.warning_gemini_day_ceiling() → tổng mọi lượt gọi Gemini ≤ 400 < 500, Mây luôn còn ≥ 100 lượt.
--   p_limits: {"geminiCallsPerMinute" 1–100000, "warnCallsPerMinute" 1–100000, "warnCallsPerDay" 1–60}, số nguyên
--   (src/features/chat/config.ts). Trần theo phút do app gửi (e2e AI giả nhân 100 như quotaLimits(mock)); trần theo
--   ngày tối đa 60 là trần cứng, không nhân khi mock.
--   Thứ tự: warn:minute → warn:day (ngày America/Los_Angeles) → gemini:minute → gemini:day (≤ ngưỡng chừa cho Mây).
--   Vượt: WARNING_QUOTA_EXCEEDED, detail {"scope": warn_minute | warn_day | gemini_minute | chat_reserve,
--   "resets_at"}; exception ở bước nào cũng rollback mọi lần cộng trước đó trong lời gọi.
create or replace function public.consume_warning_quota(p_limits jsonb)
returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_now    timestamptz := now();
  v_minute timestamptz := date_trunc('minute', v_now at time zone 'UTC') at time zone 'UTC';
  v_la_day timestamp   := date_trunc('day', v_now at time zone 'America/Los_Angeles');
  v_key    text;
  v_limit  jsonb;
  v_max    int;
begin
  if not (select public.is_admin()) then
    raise exception 'FORBIDDEN';
  end if;

  foreach v_key in array array['geminiCallsPerMinute', 'warnCallsPerMinute', 'warnCallsPerDay'] loop
    v_limit := p_limits -> v_key;
    v_max := case v_key when 'warnCallsPerDay' then 60 else 100000 end;
    -- Hai câu if riêng: SQL không bảo đảm thứ tự của or, ép kiểu ::int chỉ chạy khi đã chắc là số nguyên
    if v_limit is null or jsonb_typeof(v_limit) <> 'number' or v_limit::text !~ '^[0-9]{1,6}$' then
      raise exception 'INVALID_INPUT'
        using detail = json_build_object('field', v_key, 'max', v_max)::text;
    end if;
    if v_limit::text::int not between 1 and v_max then
      raise exception 'INVALID_INPUT'
        using detail = json_build_object('field', v_key, 'max', v_max)::text;
    end if;
  end loop;

  perform private.chat_quota_take('warn:minute', v_minute, (p_limits ->> 'warnCallsPerMinute')::int,
    'WARNING_QUOTA_EXCEEDED', 'warn_minute', v_minute + interval '1 minute');
  perform private.chat_quota_take('warn:day', v_la_day at time zone 'America/Los_Angeles',
    (p_limits ->> 'warnCallsPerDay')::int,
    'WARNING_QUOTA_EXCEEDED', 'warn_day', (v_la_day + interval '1 day') at time zone 'America/Los_Angeles');
  perform private.chat_quota_take('gemini:minute', v_minute, (p_limits ->> 'geminiCallsPerMinute')::int,
    'WARNING_QUOTA_EXCEEDED', 'gemini_minute', v_minute + interval '1 minute');
  if private.chat_quota_take('gemini:day', v_la_day at time zone 'America/Los_Angeles',
       private.warning_gemini_day_ceiling(),
       'WARNING_QUOTA_EXCEEDED', 'chat_reserve', (v_la_day + interval '1 day') at time zone 'America/Los_Angeles') = 1 then
    -- Lượt gọi đầu tiên của ngày mới (có thể là gợi ý, không phải Mây): dọn bộ đếm cũ như consume_chat_quota
    delete from private.chat_quota where window_start < v_now - interval '3 days';
  end if;

  return jsonb_build_object('ok', true);
end;
$$;

-- 5. Admin duyệt gợi ý (p_approve = true: ghi p_labels (bản admin đã sửa) vào sách) hoặc bỏ qua (sách thành "đã xét",
-- không đổi nhãn). Gợi ý không có / không còn pending (đã duyệt ở tab khác) → SUGGESTION_STATUS_CHANGED, so sau khi
-- khóa dòng. Trả book_id để app làm mới cache của sách.
create or replace function public.review_warning_suggestion(
  p_id      bigint,
  p_labels  public.content_warning[],
  p_approve boolean
)
returns bigint
language plpgsql volatile security definer set search_path = '' as $$
declare
  v_book_id bigint;
  v_status  text;
begin
  if not (select public.is_admin()) then
    raise exception 'FORBIDDEN';
  end if;

  if p_approve is null or (p_approve and (p_labels is null or array_position(p_labels, null) is not null)) then
    raise exception 'INVALID_INPUT'
      using detail = json_build_object('field', 'labels')::text;
  end if;

  select s.book_id, s.status into v_book_id, v_status
    from public.content_warning_suggestions s
   where s.id = p_id
     for update;

  if not found or v_status <> 'pending' then
    raise exception 'SUGGESTION_STATUS_CHANGED';
  end if;

  if p_approve then
    update public.books
       set content_warnings = p_labels, content_warnings_reviewed_at = now()
     where id = v_book_id;
    update public.content_warning_suggestions
       set status = 'approved', labels = p_labels, reviewed_at = now()
     where id = p_id;
  else
    update public.books
       set content_warnings_reviewed_at = now()
     where id = v_book_id;
    update public.content_warning_suggestions
       set status = 'dismissed', reviewed_at = now()
     where id = p_id;
  end if;

  return v_book_id;
end;
$$;

-- 6. Quyền gọi hàm
revoke execute on function private.content_warnings_sorted(public.content_warning[]) from public, anon, authenticated;
revoke execute on function private.user_blocks_limit() from public, anon, authenticated;
revoke execute on function private.warning_gemini_day_ceiling() from public, anon, authenticated;

revoke execute on function public.consume_warning_quota(jsonb) from public, anon;
grant  execute on function public.consume_warning_quota(jsonb) to authenticated;

revoke execute on function public.review_warning_suggestion(bigint, public.content_warning[], boolean) from public, anon;
grant  execute on function public.review_warning_suggestion(bigint, public.content_warning[], boolean) to authenticated;

commit;
